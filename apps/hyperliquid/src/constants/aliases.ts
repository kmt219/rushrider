/** Strip dex prefix (e.g. "xyz:BRENTOIL" → "BRENTOIL") and look up human alias. */
export function getMarketAlias(coin: string): string | undefined {
    const ticker = coin.includes(":") ? (coin.split(":")[1] ?? coin) : coin;
    return MARKET_ALIASES[ticker];
}
